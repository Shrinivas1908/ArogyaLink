/**
 * Translate a key into the requested language.
 * Falls back to English if the key/lang is missing.
 * @param {string} key
 * @param {string} lang
 * @returns {string}
 */
export function t(key, lang = 'en') {
  const entry = translations[key]
  if (!entry) return key
  return entry[lang] || entry['en'] || key
}

/**
 * Map a question option value → its translated label.
 * Falls back to the original English label.
 * @param {string} value  e.g. 'chest_pain'
 * @param {string} lang
 * @param {string} fallback  original English label
 * @returns {string}
 */
export function tOpt(value, lang, fallback) {
  const key = `opt_${value}`
  const entry = translations[key]
  if (!entry) return fallback
  return entry[lang] || entry['en'] || fallback
}

/**
 * Translate a question text by its question_id.
 * Falls back to the server-returned English text.
 * @param {string} questionId  e.g. 'q_chief_complaint'
 * @param {string} lang
 * @param {string} fallback
 * @returns {string}
 */
export function tQuestion(questionId, lang, fallback) {
  const entry = translations[questionId]
  if (!entry) return fallback
  return entry[lang] || entry['en'] || fallback
}
